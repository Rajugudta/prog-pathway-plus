function slugify(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function starterFor(language: string, title: string): string {
  const fn = "solve";
  switch (language) {
    case "Python":
      return `# ${title}\ndef ${fn}(*args):\n    # your code here\n    pass\n`;
    case "Java":
      return `// ${title}\nclass Solution {\n    public Object ${fn}(Object input) {\n        // your code here\n        return null;\n    }\n}\n`;
    case "C++":
      return `// ${title}\n#include <bits/stdc++.h>\nusing namespace std;\n\nint main() {\n    // your code here\n    return 0;\n}\n`;
    case "C":
      return `/* ${title} */\n#include <stdio.h>\n\nint main(void) {\n    /* your code here */\n    return 0;\n}\n`;
    case "JavaScript":
      return `// ${title}\nfunction ${fn}(input) {\n  // your code here\n}\n`;
    case "TypeScript":
      return `// ${title}\nfunction ${fn}(input: unknown): unknown {\n  // your code here\n  return null;\n}\n`;
    case "Go":
      return `// ${title}\npackage main\n\nfunc ${fn}() {\n\t// your code here\n}\n`;
    case "C#":
      return `// ${title}\npublic class Solution {\n    public object Solve(object input) {\n        // your code here\n        return null;\n    }\n}\n`;
    case "Rust":
      return `// ${title}\nfn ${fn}() {\n    // your code here\n}\n`;
    case "Kotlin":
      return `// ${title}\nfun ${fn}(): Any? {\n    // your code here\n    return null\n}\n`;
    case "Swift":
      return `// ${title}\nfunc ${fn}() -> Any? {\n    // your code here\n    return nil\n}\n`;
    default:
      return `-- ${title}\nSELECT 1;\n`;
  }
}

function build(): Problem[] {
  const out: Problem[] = [];
  let id = 1;
  for (const [topic, rows] of Object.entries(BANK)) {
    for (const [title, difficulty, statement] of rows) {
      const starter: Record<string, string> = {};
      for (const lang of GENERAL_LANGUAGES) starter[lang] = starterFor(lang, title);
      out.push({
        id,
        slug: `${slugify(title)}-${id}`,
        title,
        difficulty,
        topic,
        statement,
        languages: GENERAL_LANGUAGES,
        starter,
      });
      id += 1;
    }
  }
  return out;
}

export const PROBLEMS: Problem[] = build();
export const TOPICS: string[] = Object.keys(BANK);
export const PROBLEM_COUNT = PROBLEMS.length;

export function getProblemBySlug(slug: string): Problem | undefined {
  return PROBLEMS.find((p) => p.slug === slug);
}
